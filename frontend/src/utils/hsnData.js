/**
 * Normalizes standard identifier to match registry keys
 */
export function getHsnInfoForStandard(standard) {
  if (!standard) return null;
  const id = standard.id || standard.standard_id || '';
  
  // Exact match
  if (HSN_STANDARDS_REGISTRY[id]) {
    return HSN_STANDARDS_REGISTRY[id];
  }

  // Substring match
  const cleanId = id.toUpperCase().replace(/\s+/g, ' ');
  for (const [key, val] of Object.entries(HSN_STANDARDS_REGISTRY)) {
    const keyClean = key.toUpperCase().replace(/\s+/g, ' ');
    const numPart = keyClean.split(':')[0].replace(/[^0-9]/g, '');
    const searchNumPart = cleanId.split(':')[0].replace(/[^0-9]/g, '');
    if (numPart && searchNumPart && (cleanId.includes(keyClean) || (numPart === searchNumPart && numPart.length >= 3))) {
      return val;
    }
  }

  // If standard already has hsn_code embedded
  if (standard.hsn_code) {
    return {
      hsn_code: standard.hsn_code,
      hsn_chapter: standard.hsn_chapter || 'Harmonized Tariff Classification',
      hsn_description: standard.hsn_description || standard.title || 'Standard Classified Product',
      gst_rate: standard.gst_rate || '18%',
      qco_status: standard.qco_status || 'Current'
    };
  }

  // Intelligent fallback by sector
  const sector = (standard.sector || '').toLowerCase();
  if (sector.includes('electrical')) {
    return { hsn_code: '8516 90 00', hsn_chapter: 'Chapter 85 - Electrical Machinery', hsn_description: 'Electrical and Electronic Appliances', gst_rate: '18%', qco_status: 'Mandatory QCO' };
  }
  if (sector.includes('textile')) {
    return { hsn_code: '6302 99 00', hsn_chapter: 'Chapter 63 - Made-Up Textiles', hsn_description: 'Textiles and Bedding Articles', gst_rate: '12%', qco_status: 'Mandatory QCO' };
  }
  if (sector.includes('medical')) {
    return { hsn_code: '9018 90 99', hsn_chapter: 'Chapter 90 - Medical Instruments', hsn_description: 'Medical and Healthcare Diagnostic Equipment', gst_rate: '12%', qco_status: 'Mandatory QCO' };
  }
  if (sector.includes('footwear')) {
    return { hsn_code: '6403 99 00', hsn_chapter: 'Chapter 64 - Footwear', hsn_description: 'Footwear with Rubber or Leather Soles', gst_rate: '18%', qco_status: 'Mandatory QCO' };
  }
  if (sector.includes('cement') || sector.includes('construction')) {
    return { hsn_code: '2523 29 00', hsn_chapter: 'Chapter 25 - Cement and Mineral Products', hsn_description: 'Hydraulic and Portland Cement', gst_rate: '28%', qco_status: 'Mandatory QCO' };
  }

  return {
    hsn_code: '9983 99',
    hsn_chapter: 'Chapter 99 - Technical Testing and Compliance Services',
    hsn_description: 'Standard Certified Industrial & Consumer Product',
    gst_rate: '18%',
    qco_status: 'Active'
  };
}

/**
 * Enriches an array of standard objects with HSN metadata using JavaScript.
 */
export function enrichStandardsWithHSN(standardsList) {
  if (!Array.isArray(standardsList)) return [];
  return standardsList.map(std => {
    const hsnMeta = getHsnInfoForStandard(std);
    return {
      ...std,
      hsn_code: std.hsn_code || hsnMeta.hsn_code,
      hsn_chapter: std.hsn_chapter || hsnMeta.hsn_chapter,
      hsn_description: std.hsn_description || hsnMeta.hsn_description,
      gst_rate: std.gst_rate || hsnMeta.gst_rate,
      qco_status: std.qco_status || hsnMeta.qco_status
    };
  });
}
